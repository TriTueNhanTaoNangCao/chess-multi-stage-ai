def evaluate_board(board: chess.Board, *, claim_draw=True, check_terminal=True) -> int:
    """Centipawns from White; published tables are stored rank 8 down to 1."""
    if check_terminal:
        outcome = board.outcome(claim_draw=claim_draw)
        if outcome is not None:
            return 0 if outcome.winner is None else (30000 if outcome.winner else -30000)
    score = 0
    for sq, piece in board.piece_map().items():
        index = chess.square_mirror(sq) if piece.color else sq
        value = PIECE_VALUES[piece.piece_type] + PST_TABLES[piece.piece_type][index]
        score += value if piece.color else -value
    # Pawn shield and attacked king-ring squares. PST already rewards development.
    for color in chess.COLORS:
        king = board.king(color)
        if king is None:
            continue
        safety = 0
        for sq in board.attacks(king):
            if board.is_attacked_by(not color, sq):
                safety -= 8
            if board.piece_at(sq) == chess.Piece(chess.PAWN, color):
                safety += 6
        score += safety if color else -safety
    return score


def evaluate_relative(board: chess.Board, **kwargs) -> int:
    score = evaluate_board(board, **kwargs)
    return score if board.turn else -score
